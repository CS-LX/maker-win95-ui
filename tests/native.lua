local function point(w,fx,fy)
    layout();local l=w:GetAbsoluteLayoutForHitTest();return (l.x+l.w*(fx or .5))*UI.GetScale(),(l.y+l.h*(fy or .5))*UI.GetScale()
end
local function click(w)
    local x,y=point(w);UI.HandleMouseMove(x,y);UI.HandleMouseDown(x,y,MOUSEB_LEFT);UI.HandleMouseUp(x,y,MOUSEB_LEFT)
end
local function check(name,fn)
    checks=checks+1
    c=Win.new(root,{density=(WIN95_TEST_OPTIONS or {}).density});layout()
    local ok,err=xpcall(fn,debug.traceback)
    local clean,cleanup=pcall(function()c:Destroy()end)
    if not ok or not clean then failures=failures+1;print('[Win95] FAIL '..name..' '..tostring(err or cleanup))
    else print('[Win95] check '..name..' OK') end
    UI.ClearFocus();collectgarbage('collect')
end
