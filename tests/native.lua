local function eq(a,b,why) assert(a==b,(why or 'mismatch')..': '..tostring(a)..' ~= '..tostring(b)) end
local function near(a,b) assert(math.abs(a-b)<.01,tostring(a)..' ~= '..tostring(b)) end
local c,root
